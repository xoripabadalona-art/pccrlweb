"""Split the pepperoni toppings render into individual slice sprites.

Finds every connected blob of opaque pixels in the toppings layer, packs them
into one atlas image and writes their original positions to a TS data file, so
the hero can float and spin each slice on its own.

Usage: python3 scripts/split-pepperoni-sprites.py
"""
from collections import deque
from pathlib import Path
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "public/images/pizzas-3d/toppings-pepperoni-v2.webp"
ATLAS = ROOT / "public/images/pizzas-3d/pepperoni-sprites.webp"
DATA = ROOT / "src/data/pepperoniSprites.ts"
MIN_AREA = 450
# Odd kernel size for the erosion that separates touching slices
ERODE = 15
PAD = 2
ATLAS_W = 1024

im = Image.open(SRC).convert("RGBA")
W, H = im.size
alpha = im.getchannel("A").tobytes()
N = W * H


def neighbours(p):
    x, y = p % W, p // W
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            nx, ny = x + dx, y + dy
            if (dx or dy) and 0 <= nx < W and 0 <= ny < H:
                yield ny * W + nx


# 1. Erode the mask so slices that only touch (or overlap a little) fall apart
#    into separate cores, then label the cores.
solid = im.getchannel("A").point(lambda v: 255 if v > 40 else 0)
core = solid.filter(ImageFilter.MinFilter(ERODE)).tobytes()
label = [0] * N
count = 0
for start in range(N):
    if label[start] or not core[start]:
        continue
    count += 1
    q = deque([start])
    label[start] = count
    size = 1
    while q:
        p = q.popleft()
        for n in neighbours(p):
            if not label[n] and core[n]:
                label[n] = count
                size += 1
                q.append(n)

# 2. Grow every core back over the full mask; each pixel joins its nearest core.
q = deque(p for p in range(N) if label[p])
while q:
    p = q.popleft()
    for n in neighbours(p):
        if not label[n] and alpha[n] > 40:
            label[n] = label[p]
            q.append(n)

groups = {}
for p in range(N):
    if label[p]:
        groups.setdefault(label[p], []).append(p)
comps = [pix for pix in groups.values() if len(pix) >= MIN_AREA]

sprites = []
for pix in comps:
    xs = [p % W for p in pix]
    ys = [p // W for p in pix]
    x0, y0 = max(min(xs) - PAD, 0), max(min(ys) - PAD, 0)
    x1, y1 = min(max(xs) + PAD + 1, W), min(max(ys) + PAD + 1, H)
    mask = Image.new("L", (x1 - x0, y1 - y0), 0)
    mp = mask.load()
    for p in pix:
        mp[p % W - x0, p // W - y0] = 255
    # soften the cut so anti-aliased edges survive
    crop = im.crop((x0, y0, x1, y1))
    a = crop.getchannel("A")
    grown = mask.filter(ImageFilter.MaxFilter(3))
    crop.putalpha(Image.composite(a, Image.new("L", a.size, 0), grown))
    sprites.append({"x": x0, "y": y0, "w": x1 - x0, "h": y1 - y0, "img": crop, "area": len(pix)})

# shelf packing, tallest first
order = sorted(range(len(sprites)), key=lambda i: -sprites[i]["h"])
cx = cy = shelf = 0
for i in order:
    s = sprites[i]
    if cx + s["w"] > ATLAS_W:
        cx, cy, shelf = 0, cy + shelf, 0
    s["ax"], s["ay"] = cx, cy
    cx += s["w"]
    shelf = max(shelf, s["h"])
atlas_h = cy + shelf
atlas = Image.new("RGBA", (ATLAS_W, atlas_h), (0, 0, 0, 0))
for s in sprites:
    atlas.paste(s["img"], (s["ax"], s["ay"]))
atlas.save(ATLAS, "WEBP", quality=88, method=6)

rows = ",\n".join(
    f"  {{ x: {s['x']}, y: {s['y']}, w: {s['w']}, h: {s['h']}, ax: {s['ax']}, ay: {s['ay']} }}"
    for s in sprites
)
DATA.write_text(
    "// Generated by scripts/split-pepperoni-sprites.py — do not edit by hand.\n"
    "// Positions are in the 1280×800 frame of the pepperoni toppings layer.\n\n"
    "export interface PepperoniSprite {\n  x: number;\n  y: number;\n  w: number;\n  h: number;\n"
    "  /** top-left of this slice inside the atlas image */\n  ax: number;\n  ay: number;\n}\n\n"
    f"export const PEPPERONI_FRAME = {{ w: {W}, h: {H} }};\n\n"
    "export const PEPPERONI_ATLAS = {\n"
    "  src: '/images/pizzas-3d/pepperoni-sprites.webp',\n"
    f"  w: {ATLAS_W},\n  h: {atlas_h},\n}};\n\n"
    f"export const PEPPERONI_SPRITES: PepperoniSprite[] = [\n{rows},\n];\n"
)
print(len(sprites), "sprites; atlas", ATLAS_W, "x", atlas_h, "; areas", sorted(s["area"] for s in sprites)[:5], "…")
